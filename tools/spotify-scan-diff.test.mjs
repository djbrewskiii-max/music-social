import assert from 'node:assert/strict';
import { compareSpotifyScans } from '../src/spotify-scan-diff.ts';
const track=(song,artist='Artist')=>({song,artist,spotifyTrackUrl:null});
const playlist=(id,songs,status='ready')=>({id,url:'https://open.spotify.com/playlist/'+id,title:id,tracks:songs.map(s=>track(s)),status,observedRows:songs.length,limited:false});
const scan=(...playlists)=>({userId:'user',url:'https://open.spotify.com/user/user',playlists,totalVisibleLinks:playlists.length,warnings:[]});
const first=compareSpotifyScans(scan(playlist('a',['One','Two'])),null);
assert.equal(first.firstScan,true);
assert.deepEqual(first.newByPlaylist.a,[]);
const second=compareSpotifyScans(scan(playlist('a',['One','Two','Three'])),first.history);
assert.equal(second.newByPlaylist.a.length,1);
assert.ok(second.newByPlaylist.a[0].includes('three'));
const rearranged=compareSpotifyScans(scan(playlist('a',['Three','One'])),second.history);
assert.deepEqual(rearranged.newByPlaylist.a,[]);
assert.equal(rearranged.removedFromView.a,1);
const unavailable=compareSpotifyScans(scan(playlist('a',[],'unavailable')),rearranged.history);
assert.deepEqual(unavailable.history.playlists.a,rearranged.history.playlists.a);
const returned=compareSpotifyScans(scan(playlist('a',['Two','Three'])),unavailable.history);
assert.deepEqual(returned.newByPlaylist.a,[]);
const addedPlaylist=compareSpotifyScans(scan(playlist('b',['Four'])),returned.history);
assert.deepEqual(addedPlaylist.newByPlaylist.b,[]);
console.log('PASS: new visible tracks detected, baseline respected, order changes ignored, unreadable pages preserved');
